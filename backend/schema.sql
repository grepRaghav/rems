-- ====================================================================
-- Renewable Energy Management System (REMS)
-- Oracle Database 11g Compatible Schema
-- ====================================================================

-- 1. APP_USERS (Authentication & RBAC)
CREATE TABLE APP_USERS (
    USER_ID VARCHAR2(36) PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    FULL_NAME VARCHAR2(100) NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'admin' NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL
);

-- 2. POWER_PLANTS (Core Generation Facilities)
CREATE TABLE POWER_PLANTS (
    PLANT_ID VARCHAR2(20) PRIMARY KEY,
    PLANT_NAME VARCHAR2(100) NOT NULL,
    ENERGY_TYPE VARCHAR2(30) NOT NULL,
    LOCATION VARCHAR2(100) NOT NULL,
    CAPACITY_KW NUMBER(12, 2) NOT NULL,
    INSTALL_DATE DATE NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'Active' NOT NULL,
    OPERATOR_NAME VARCHAR2(100),
    CONSTRAINT CHK_PLANT_STATUS CHECK (STATUS IN ('Active', 'Maintenance', 'Inactive', 'Decommissioned'))
);

-- 3. EQUIPMENT (Hardware Assets associated with plants)
CREATE TABLE EQUIPMENT (
    EQUIPMENT_ID VARCHAR2(20) PRIMARY KEY,
    PLANT_ID VARCHAR2(20) NOT NULL,
    EQUIPMENT_NAME VARCHAR2(100) NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    QUANTITY NUMBER(8) DEFAULT 1 NOT NULL,
    UNIT_COST NUMBER(12, 2) DEFAULT 0.00 NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'Operational' NOT NULL,
    CONSTRAINT FK_EQUIPMENT_PLANT FOREIGN KEY (PLANT_ID) 
        REFERENCES POWER_PLANTS(PLANT_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_EQUIP_STATUS CHECK (STATUS IN ('Operational', 'Needs Service', 'Under Repair', 'Offline'))
);

-- 4. ENERGY_GENERATION (Log of power generation outputs)
CREATE TABLE ENERGY_GENERATION (
    GENERATION_ID VARCHAR2(20) PRIMARY KEY,
    PLANT_ID VARCHAR2(20) NOT NULL,
    GENERATION_DATE DATE NOT NULL,
    ENERGY_KWH NUMBER(12, 2) NOT NULL,
    EFFICIENCY_PERCENT NUMBER(5, 2) NOT NULL,
    PEAK_OUTPUT_KW NUMBER(12, 2),
    REMARKS VARCHAR2(250),
    CONSTRAINT FK_GEN_PLANT FOREIGN KEY (PLANT_ID) 
        REFERENCES POWER_PLANTS(PLANT_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_EFFICIENCY CHECK (EFFICIENCY_PERCENT >= 0 AND EFFICIENCY_PERCENT <= 100)
);

-- 5. MAINTENANCE_RECORDS (Service logs for equipment)
CREATE TABLE MAINTENANCE_RECORDS (
    RECORD_ID VARCHAR2(20) PRIMARY KEY,
    EQUIPMENT_ID VARCHAR2(20) NOT NULL,
    MAINTENANCE_DATE DATE NOT NULL,
    MAINTENANCE_TYPE VARCHAR2(30) NOT NULL,
    TECHNICIAN_NAME VARCHAR2(100) NOT NULL,
    COST NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'Completed' NOT NULL,
    NOTES VARCHAR2(300),
    CONSTRAINT FK_MAINT_EQUIP FOREIGN KEY (EQUIPMENT_ID) 
        REFERENCES EQUIPMENT(EQUIPMENT_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_MAINT_STATUS CHECK (STATUS IN ('Scheduled', 'In Progress', 'Completed', 'Cancelled'))
);

-- 6. DISPOSABLE_TEST_TABLE (Safe Sandbox for DDL Demonstrations)
CREATE TABLE DISPOSABLE_TEST_TABLE (
    TEST_ID VARCHAR2(20) PRIMARY KEY,
    SAMPLE_NAME VARCHAR2(50) NOT NULL,
    METRIC_VALUE NUMBER(10, 2),
    CREATED_AT DATE DEFAULT SYSDATE
);

-- Commit schema creation
COMMIT;
